import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(root, '../..');
const upstreamRoot = resolve(
  repositoryRoot,
  process.env.MERMAID_SOURCE_DIR ?? 'build/upstream/mermaid-src',
);
const fixtureRoot = resolve(
  upstreamRoot,
  'e2e/platform/dev-diagrams/layout-tests/swimlanes',
);

const fixtureIds = [
  '10-node-placement',
  '14-messy-layout',
  '15-border-hugging',
  '15-border-hugging-lr',
  '16-intake-cycle-lr',
  '4-car-fun-sales-tb',
  '5-car-fun-sales-wide-tb',
  '6-legal-constr-sales',
  '7-car-sales-constr',
  '8-query-process-2',
  'mermaid-work',
  'pebr-3-process-too-wide-in-lane',
  'query-process',
  'simple-2',
];

const cases = fixtureIds.map((fixtureId) => {
  const sourcePath = resolve(fixtureRoot, `${fixtureId}.mmd`);
  const source = readFileSync(sourcePath, 'utf8').trimEnd();
  if (!/^\s*swimlane(?:-beta)?\b/m.test(source)) {
    throw new Error(`${sourcePath} does not select the Swimlanes renderer`);
  }
  return {
    id: `ddlt_swimlanes_${fixtureId.replaceAll('-', '_')}`,
    fixtureId: `swimlanes/${fixtureId}`,
    kind: 'swimlanes',
    title: `Upstream DDLT: ${fixtureId}`,
    source,
    layout: 'swimlane',
    aspectRatio: 1.6,
    expectedTexts: [],
  };
});

const jsTarget = resolve(root, 'swimlane-ddlt-corpus.mjs');
writeFileSync(
  jsTarget,
  [
    '// Generated by generate-swimlane-ddlt-corpus.mjs. Do not edit by hand.',
    `export const cases = ${JSON.stringify(cases, null, 2)};`,
    '',
  ].join('\n'),
);
console.log(`Generated ${jsTarget}`);

const kotlinOutputs = [
  {
    packageName: 'com.swithun.cmpmermaid.debugui.generated',
    target: resolve(
      repositoryRoot,
      'mermaid-debug-ui/src/commonMain/kotlin/com/swithun/cmpmermaid/debugui/generated/' +
        'SwimlaneDdltCorpus.kt',
    ),
  },
  {
    packageName: 'com.swithun.cmpmermaid.core.generated',
    target: resolve(
      repositoryRoot,
      'mermaid-core/src/commonTest/kotlin/com/swithun/cmpmermaid/core/generated/' +
        'SwimlaneDdltCorpus.kt',
    ),
  },
];

for (const output of kotlinOutputs) {
  mkdirSync(dirname(output.target), { recursive: true });
  writeFileSync(output.target, renderKotlin(output.packageName));
  console.log(`Generated ${output.target}`);
}

function renderKotlin(packageName) {
  const entries = cases.map((entry) => `    StabilityCorpusCase(
        id = ${kotlinString(entry.id)},
        diagramId = "swimlanes",
        title = ${kotlinString(entry.title)},
        scenario = ${kotlinString(`Mermaid 12.0.0 DDLT fixture ${entry.fixtureId}`)},
        layout = "swimlane",
        initialAspectRatio = 1.6f,
        source = """
${indentSource(entry.source, 12)}
        """.trimIndent(),
        expectedTexts = emptyList(),
        features = setOf("upstream-ddlt", ${kotlinString(entry.fixtureId)}),
    )`).join(',\n');
  return `// Generated by tools/official-reference/generate-swimlane-ddlt-corpus.mjs.
// Do not edit by hand.
package ${packageName}

internal val swimlaneDdltCorpusCases: List<StabilityCorpusCase> = listOf(
${entries},
)
`;
}

function kotlinString(value) {
  return JSON.stringify(value);
}

function indentSource(source, spaces) {
  const prefix = ' '.repeat(spaces);
  return source
    .split('\n')
    .map((line) => (line.trim().length === 0 ? '' : `${prefix}${line}`))
    .join('\n');
}
